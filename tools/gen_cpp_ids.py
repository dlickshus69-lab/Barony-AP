"""
Writes client/src/archipelago_ids.hpp from apworld/barony/data.py, so the game client
and the APWorld always agree on item and location numbers.

Run from the repository root:  python tools/gen_cpp_ids.py
"""
import importlib.util
import pathlib
import sys
import types

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "apworld" / "barony" / "data.py"
OUT = ROOT / "client" / "src" / "archipelago_ids.hpp"

spec = importlib.util.spec_from_file_location("barony_data", DATA)
data = importlib.util.module_from_spec(spec)
sys.modules["barony_data"] = data
spec.loader.exec_module(data)

lines = [
    "// GENERATED by tools/gen_cpp_ids.py from apworld/barony/data.py. Do not edit by hand.",
    "#pragma once",
    "#include <cstdint>",
    "",
    "namespace ap_ids {",
    f"constexpr int64_t BASE_ID = {data.BASE_ID};",
    f"constexpr int64_t FLOOR_OFFSET = {data.FLOOR_OFFSET};",
    f"constexpr int64_t LEVEL_OFFSET = {data.LEVEL_OFFSET};",
    f"constexpr int64_t KILL_OFFSET = {data.KILL_OFFSET};",
    f"constexpr int64_t BESTIARY_OFFSET = {data.BESTIARY_OFFSET};",
    f"constexpr int64_t PICKUP_OFFSET = {data.PICKUP_OFFSET};",
    f"constexpr int64_t SHOP_OFFSET = {data.SHOP_OFFSET};",
    f"constexpr int64_t BOSS_OFFSET = {data.BOSS_OFFSET};",
    f"constexpr int64_t SPECIAL_OFFSET = {data.SPECIAL_OFFSET};",
    f"constexpr int MAX_FLOOR = {data.MAX_FLOOR};",
    f"constexpr int FLOORS_PER_SECTION = {data.FLOORS_PER_SECTION};",
    "",
    "// Items",
]
for name, info in data.ITEMS.items():
    lines.append(f"constexpr int64_t ITEM_{info.cpp_name} = {data.BASE_ID + info.code}; // {name}")

lines += ["", "struct MonsterEntry { int index; const char* name; int monster; int depth; bool early; };",
          "struct BossEntry { int index; const char* name; int monster; int floor; };",
          "struct AreaEntry { int index; const char* name; const char* match; int depth; };",
          "} // namespace ap_ids", "",
          "// These tables need Barony's Monster enum, so include monster.hpp before this file.",
          "namespace ap_ids {",
          "static const MonsterEntry BESTIARY[] = {"]
for m in data.BESTIARY:
    lines.append(f'    {{ {m.index}, "{m.name}", {m.enum_name}, {m.depth}, {"true" if m.early else "false"} }},')
lines += ["};", "static const BossEntry BOSSES[] = {"]
for b in data.BOSSES:
    lines.append(f'    {{ {b.index}, "{b.location_name}", {b.enum_name}, {b.floor} }},')
lines += ["};", "static const AreaEntry SPECIAL_AREAS[] = {"]
for a in data.SPECIAL_AREAS:
    lines.append(f'    {{ {a.index}, "{a.name}", "{a.map_match}", {a.depth} }},')
lines += ["};", "} // namespace ap_ids", ""]

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}")
